"""Разбор строки команды на имя команды и аргументы."""

import shlex


class ParseError(Exception):
    """Ошибка разбора строки команды (например, незакрытая кавычка)."""


def parse_command(line):
    """Разбить строку команды на список слов с учётом кавычек.

    Аргументы в одинарных или двойных кавычках считаются одним словом:
    строка ``cd "My Folder"`` превращается в ``['cd', 'My Folder']``.

    :param line: строка, введённая пользователем
    :return: список слов; пустой список для пустой строки
    :raises ParseError: если в строке есть незакрытая кавычка
    """
    try:
        return shlex.split(line)
    except ValueError as error:
        raise ParseError("ошибка разбора: незакрытая кавычка") from error
